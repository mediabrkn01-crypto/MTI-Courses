-- ── 1. Admin users table (deny-all to public) ────────────────────────────────
-- Admin accounts are linked here after Supabase Auth account creation.
-- bootstrap-admin.js inserts the first row server-side via service role.
CREATE TABLE IF NOT EXISTS public.admin_users (
  auth_user_id  uuid PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  created_by    uuid
);
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
-- Zero policies = deny all non-service-role access (service role bypasses RLS)

-- ── 2. is_admin() SECURITY DEFINER helper ─────────────────────────────────────
-- Called by: admin login flow (auth.js), Edge Functions via service role check.
-- Returns true only if the current JWT's uid is in admin_users.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.admin_users
    WHERE auth_user_id = auth.uid()
  );
$$;

-- Grant execute to authenticated users so frontend can call it via rpc()
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;

-- ── 3. Security audit log ─────────────────────────────────────────────────────
-- Tracks admin actions like password changes. Non-public (no RLS policies).
CREATE TABLE IF NOT EXISTS public.security_audit_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid,
  event_type    text NOT NULL,
  target_type   text,
  target_id     text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  metadata      jsonb
);
ALTER TABLE public.security_audit_log ENABLE ROW LEVEL SECURITY;
-- No public policies = only service role can write (Edge Function)

-- ── 4. Clear password_reset_required for ALL existing students ────────────────
-- Students migrated with password_reset_required=true were blocked from login.
-- Admin will now set passwords via "Set Password" in Manage Student.
-- The force-reset overlay is removed from the login flow in auth.js.
UPDATE public.students
SET password_reset_required = false
WHERE password_reset_required = true;

